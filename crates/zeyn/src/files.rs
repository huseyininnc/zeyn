    /// Who may download and who may upload the files of a store. A plain permission name is
    /// both; [`FileAccess::read`] with [`FileAccess::write`] splits them, so readers can open
    /// files they may not add to.
    ///
    /// ```ignore
    /// Feature::new("catalog").files(
    ///     IMAGES,
    ///     FileAccess::read("catalog.product.read").write("catalog.product.write"),
    ///     store,
    /// )
    /// ```
    #[derive(Clone, Copy, Debug, PartialEq, Eq)]
    pub struct FileAccess {
        pub read: &'static str,
        pub write: &'static str,
    }

    impl FileAccess {
        /// Downloads need `permission`; uploads need it too until [`FileAccess::write`] names
        /// another one.
        pub fn read(permission: &'static str) -> Self {
            Self {
                read: permission,
                write: permission,
            }
        }

        /// Uploads need `permission`.
        pub fn write(mut self, permission: &'static str) -> Self {
            self.write = permission;
            self
        }
    }

    impl From<&'static str> for FileAccess {
        fn from(permission: &'static str) -> Self {
            Self::read(permission)
        }
    }

    fn not_found() -> Error {
        Error::NotFound
    }

    fn io(e: std::io::Error) -> Error {
        Error::Internal(format!("file store: {e}"))
    }

    /// Files on the local disk under one folder: `{id}.bin` holds the bytes and `{id}.json` the
    /// metadata. Uploads are written to `{id}.part` and renamed when complete, so a stopped
    /// upload never shows up. Writing happens on the blocking pool, one chunk at a time.
    ///
    /// An upload no saved record claimed yet has an empty marker file in
    /// `unclaimed/{user key}/{id}`; files without one, such as those of older versions, count
    /// as claimed. Unclaimed files are removed only when [`DiskStore::unclaimed_for`] is set:
    /// then an upload runs a sweep at most once per [`STALE_PART`], or once per grace period
    /// when that is shorter (at least a second apart), which removes the files whose marker is
    /// older than the grace period.
    #[derive(Clone)]
    pub struct DiskStore {
        root: Arc<PathBuf>,
        /// When the last sweep of stale `.part` files ran, in seconds since the epoch.
        swept: Arc<std::sync::atomic::AtomicU64>,
        /// How long unclaimed files are kept; `None` keeps them.
        grace: Option<std::time::Duration>,
    }

    impl DiskStore {
        /// A store in `root`, created on the first upload. Unclaimed uploads are kept until
        /// [`DiskStore::unclaimed_for`] says otherwise.
        pub fn new(root: impl Into<PathBuf>) -> Self {
            DiskStore {
                root: Arc::new(root.into()),
                swept: Arc::default(),
                grace: None,
            }
        }

        /// Removes an upload no saved record claimed within `grace`. Turn it on only when
        /// every path that saves a file of this store claims it (forms, `FileDrop`, `Composer`
        /// and API actions do); code that keeps an uploaded id in some other way must call
        /// [`FileStore::claim`] itself.
        pub fn unclaimed_for(mut self, grace: std::time::Duration) -> Self {
            self.grace = Some(grace);
            self
        }

        /// The folder of the unclaimed markers of one user in one tenant, named by a hash of
        /// both, so no user id ever becomes a path.
        fn unclaimed_dir(&self, owner: Option<&str>, tenant: Option<&str>) -> PathBuf {
            let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
            for b in format!("{tenant:?}\u{0}{owner:?}").bytes() {
                hash ^= u64::from(b);
                hash = hash.wrapping_mul(0x0100_0000_01b3);
            }
            self.root
                .join("unclaimed")
                .join(format!("{hash:016x}"))
        }

        fn path(&self, id: &str, ext: &str) -> Result<PathBuf> {
            if !valid_file_id(id) {
                return Err(not_found());
            }
            Ok(self.root.join(format!("{id}.{ext}")))
        }
    }

    /// How old a `.part` file of a stopped upload must be before a sweep removes it.
    pub const STALE_PART: std::time::Duration = std::time::Duration::from_secs(3600);

    /// Removes the `.part` files under `root` older than `max_age`: uploads stopped by a crash
    /// or a restart ([`STALE_PART`] for a [`DiskStore`]). Returns how many it removed.
    pub(crate) fn sweep_parts(root: &std::path::Path, max_age: std::time::Duration) -> u64 {
        let Ok(dir) = std::fs::read_dir(root) else {
            return 0;
        };
        let mut removed = 0;
        for entry in dir.flatten() {
            let path = entry.path();
            let stale = path.extension() == Some(std::ffi::OsStr::new("part"))
                && entry
                    .metadata()
                    .and_then(|m| m.modified())
                    .ok()
                    .and_then(|m| m.elapsed().ok())
                    .is_some_and(|age| age > max_age);
            if stale && std::fs::remove_file(&path).is_ok() {
                removed += 1;
            }
        }
        removed
    }

    /// Removes a file, a missing one being fine.
    fn remove(path: &std::path::Path) -> std::io::Result<()> {
        match std::fs::remove_file(path) {
            Err(e) if e.kind() != std::io::ErrorKind::NotFound => Err(e),
            _ => Ok(()),
        }
    }

    /// Removes the files under `root` whose unclaimed marker is older than `grace`, and the
    /// markers. A marker is removed first, so a claim that removed it already keeps the file.
    /// A file whose metadata cannot be read is kept and logged. Returns how many files it
    /// removed.
    pub(crate) fn sweep_unclaimed(root: &std::path::Path, grace: std::time::Duration) -> u64 {
        let Ok(users) = std::fs::read_dir(root.join("unclaimed")) else {
            return 0;
        };
        let mut removed = 0;
        for user in users.flatten() {
            let Ok(markers) = std::fs::read_dir(user.path()) else {
                continue;
            };
            for marker in markers.flatten() {
                let id = marker
                    .file_name()
                    .to_string_lossy()
                    .into_owned();
                let stale = valid_file_id(&id) && age(&marker).is_some_and(|age| age > grace);
                if !stale {
                    continue;
                }
                let json = root.join(format!("{id}.json"));
                if let Err(Error::Internal(e)) = read_meta(&json) {
                    tracing::error!(file = %id, error = %e, "unclaimed file kept: its metadata cannot be read");
                    continue;
                }
                if std::fs::remove_file(marker.path()).is_ok() {
                    let _ = remove(&root.join(format!("{id}.bin")));
                    let _ = remove(&json);
                    removed += 1;
                }
            }
        }
        removed
    }

    /// Time since a directory entry was last written.
    fn age(entry: &std::fs::DirEntry) -> Option<std::time::Duration> {
        entry
            .metadata()
            .and_then(|m| m.modified())
            .ok()
            .and_then(|m| m.elapsed().ok())
    }

    impl FileStore for DiskStore {
        fn put(&self, mut meta: FileMeta, mut chunks: FileChunks) -> BoxFuture<Result<()>> {
            let paths = (
                self.path(&meta.id, "part"),
                self.path(&meta.id, "bin"),
                self.path(&meta.id, "json"),
            );
            let root = self.root.clone();
            let grace = self.grace;
            let now = std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .map_or(0, |d| d.as_secs());
            let last = self
                .swept
                .load(std::sync::atomic::Ordering::Relaxed);
            let every = grace
                .map_or(STALE_PART, |g| STALE_PART.min(g))
                .as_secs()
                .max(1);
            let sweep = now.saturating_sub(last) >= every
                && self
                    .swept
                    .compare_exchange(
                        last,
                        now,
                        std::sync::atomic::Ordering::Relaxed,
                        std::sync::atomic::Ordering::Relaxed,
                    )
                    .is_ok();
            Box::pin(async move {
                let (part, bin, json) = (paths.0?, paths.1?, paths.2?);
                let work = tokio::task::spawn_blocking(move || {
                    std::fs::create_dir_all(&*root).map_err(io)?;
                    if sweep {
                        sweep_parts(&root, STALE_PART);
                        if let Some(grace) = grace {
                            sweep_unclaimed(&root, grace);
                        }
                    }
                    let mut file = std::fs::File::create_new(&part).map_err(io)?;
                    let written = (|| {
                        let mut size = 0u64;
                        while let Some(chunk) = chunks.blocking_next() {
                            let chunk = chunk.map_err(io)?;
                            file.write_all(&chunk).map_err(io)?;
                            size += chunk.len() as u64;
                        }
                        file.sync_all().map_err(io)?;
                        Ok::<_, Error>(size)
                    })();
                    drop(file);
                    let size = match written {
                        Ok(size) => size,
                        Err(e) => {
                            let _ = std::fs::remove_file(&part);
                            return Err(e);
                        }
                    };
                    meta.size = size;
                    let text =
                        serde_json::to_vec(&meta).map_err(|e| Error::Internal(e.to_string()))?;
                    std::fs::write(&json, text).map_err(io)?;
                    std::fs::rename(&part, &bin).map_err(io)
                });
                work.await
                    .map_err(|e| Error::Internal(e.to_string()))?
            })
        }

        fn get(&self, id: String) -> BoxFuture<Result<StoredFile>> {
            let paths = (self.path(&id, "bin"), self.path(&id, "json"));
            Box::pin(async move {
                let (bin, json) = (paths.0?, paths.1?);
                tokio::task::spawn_blocking(move || {
                    let meta: FileMeta = read_meta(&json)?;
                    let file = std::fs::File::open(&bin).map_err(|_| not_found())?;
                    Ok(StoredFile {
                        meta,
                        reader: Box::new(file),
                    })
                })
                .await
                .map_err(|e| Error::Internal(e.to_string()))?
            })
        }

        fn meta(&self, id: String) -> BoxFuture<Result<FileMeta>> {
            let json = self.path(&id, "json");
            Box::pin(async move {
                let json = json?;
                tokio::task::spawn_blocking(move || read_meta(&json))
                    .await
                    .map_err(|e| Error::Internal(e.to_string()))?
            })
        }

        fn delete(&self, id: String) -> BoxFuture<Result<()>> {
            let paths = (self.path(&id, "bin"), self.path(&id, "json"));
            let this = self.clone();
            Box::pin(async move {
                let (bin, json) = (paths.0?, paths.1?);
                tokio::task::spawn_blocking(move || {
                    if let Ok(meta) = read_meta(&json) {
                        let dir = this.unclaimed_dir(meta.owner.as_deref(), meta.tenant.as_deref());
                        remove(&dir.join(&id)).map_err(io)?;
                    }
                    for p in [bin, json] {
                        remove(&p).map_err(io)?;
                    }
                    Ok(())
                })
                .await
                .map_err(|e| Error::Internal(e.to_string()))?
            })
        }

        fn mark_unclaimed(&self, meta: FileMeta) -> BoxFuture<Result<()>> {
            let dir = self.unclaimed_dir(meta.owner.as_deref(), meta.tenant.as_deref());
            let valid = valid_file_id(&meta.id);
            Box::pin(async move {
                if !valid {
                    return Err(not_found());
                }
                tokio::task::spawn_blocking(move || {
                    std::fs::create_dir_all(&dir).map_err(io)?;
                    std::fs::File::create(dir.join(&meta.id))
                        .map(drop)
                        .map_err(io)
                })
                .await
                .map_err(|e| Error::Internal(e.to_string()))?
            })
        }

        fn claim(&self, ids: Vec<String>) -> BoxFuture<Result<()>> {
            let this = self.clone();
            Box::pin(async move {
                tokio::task::spawn_blocking(move || {
                    let mut failed = None;
                    for id in ids {
                        let Ok(json) = this.path(&id, "json") else {
                            continue;
                        };
                        let markers: Vec<PathBuf> = match read_meta(&json) {
                            Ok(meta) => vec![
                                this.unclaimed_dir(meta.owner.as_deref(), meta.tenant.as_deref())
                                    .join(&id),
                            ],
                            Err(Error::NotFound) => continue,
                            Err(e) => {
                                tracing::error!(file = %id, error = ?e, "claimed file has unreadable metadata; looking for its marker in every folder");
                                std::fs::read_dir(this.root.join("unclaimed"))
                                    .map(|users| {
                                        users
                                            .flatten()
                                            .map(|u| u.path().join(&id))
                                            .collect()
                                    })
                                    .unwrap_or_default()
                            }
                        };
                        for marker in markers {
                            if let Err(e) = remove(&marker) {
                                tracing::error!(file = %id, error = %e, "claimed file could not be marked as claimed");
                                failed = Some(io(e));
                            }
                        }
                    }
                    failed.map_or(Ok(()), Err)
                })
                .await
                .map_err(|e| Error::Internal(e.to_string()))?
            })
        }

        fn unclaimed(
            &self,
            owner: Option<String>,
            tenant: Option<String>,
        ) -> BoxFuture<Result<usize>> {
            let dir = self.unclaimed_dir(owner.as_deref(), tenant.as_deref());
            let grace = self.grace.unwrap_or(UNCLAIMED_GRACE);
            Box::pin(async move {
                tokio::task::spawn_blocking(move || {
                    std::fs::read_dir(&dir).map_or(0, |markers| {
                        markers
                            .flatten()
                            .filter(|m| age(m).is_none_or(|age| age <= grace))
                            .count()
                    })
                })
                .await
                .map_err(|e| Error::Internal(e.to_string()))
            })
        }
    }

    fn read_meta(path: &std::path::Path) -> Result<FileMeta> {
        let text = std::fs::read(path).map_err(|_| not_found())?;
        serde_json::from_slice(&text).map_err(|e| Error::Internal(e.to_string()))
    }

    type Held = HashMap<String, (FileMeta, Arc<[u8]>)>;

    /// Files in memory, for tests and demos. Capped by total bytes; an upload that would pass
    /// the cap is refused. Unlike [`DiskStore`] it holds every file whole. With
    /// [`MemoryStore::unclaimed_for`], each upload first removes the files left unclaimed longer
    /// than the grace period.
    #[derive(Clone)]
    pub struct MemoryStore {
        files: Arc<Mutex<Held>>,
        /// Unclaimed files by id, with the time they were marked.
        unclaimed: Arc<Mutex<HashMap<String, std::time::Instant>>>,
        cap: u64,
        /// How long unclaimed files are kept; `None` keeps them.
        grace: Option<std::time::Duration>,
    }

    impl Default for MemoryStore {
        fn default() -> Self {
            MemoryStore::new(64 * 1024 * 1024)
        }
    }

    impl MemoryStore {
        /// A store that holds at most `cap` bytes in all.
        pub fn new(cap: u64) -> Self {
            MemoryStore {
                files: Arc::new(Mutex::new(HashMap::new())),
                unclaimed: Arc::default(),
                cap,
                grace: None,
            }
        }

        /// Removes an upload no saved record claimed within `grace`, on the next upload. See
        /// [`DiskStore::unclaimed_for`].
        pub fn unclaimed_for(mut self, grace: std::time::Duration) -> Self {
            self.grace = Some(grace);
            self
        }

        /// Removes the files unclaimed for longer than the grace period.
        fn sweep(&self) {
            let Some(grace) = self.grace else {
                return;
            };
            let (Ok(mut files), Ok(mut unclaimed)) = (self.files.lock(), self.unclaimed.lock())
            else {
                return;
            };
            unclaimed.retain(|id, since| {
                let keep = since.elapsed() <= grace;
                if !keep {
                    files.remove(id);
                }
                keep
            });
        }

        /// Ids of the stored files, for tests.
        pub fn ids(&self) -> Vec<String> {
            self.files
                .lock()
                .map(|f| f.keys().cloned().collect())
                .unwrap_or_default()
        }

        fn used(&self) -> u64 {
            self.files
                .lock()
                .map(|f| f.values().map(|(m, _)| m.size).sum())
                .unwrap_or(0)
        }
    }

    impl FileStore for MemoryStore {
        fn put(&self, mut meta: FileMeta, mut chunks: FileChunks) -> BoxFuture<Result<()>> {
            let this = self.clone();
            Box::pin(async move {
                this.sweep();
                let room = this.cap.saturating_sub(this.used());
                let mut data = Vec::new();
                while let Some(chunk) = chunks.next().await {
                    let chunk = chunk.map_err(io)?;
                    if (data.len() + chunk.len()) as u64 > room {
                        return Err(Error::Denied(Text::key("zeyn.files.store_full")));
                    }
                    data.extend_from_slice(&chunk);
                }
                meta.size = data.len() as u64;
                let mut files = this
                    .files
                    .lock()
                    .map_err(|_| Error::Internal("file store lock".into()))?;
                files.insert(meta.id.clone(), (meta, data.into()));
                Ok(())
            })
        }

        fn get(&self, id: String) -> BoxFuture<Result<StoredFile>> {
            let found = self
                .files
                .lock()
                .ok()
                .and_then(|f| f.get(&id).cloned());
            Box::pin(async move {
                let (meta, data) = found.ok_or_else(not_found)?;
                Ok(StoredFile {
                    meta,
                    reader: Box::new(Cursor::new(data)),
                })
            })
        }

        fn meta(&self, id: String) -> BoxFuture<Result<FileMeta>> {
            let found = self
                .files
                .lock()
                .ok()
                .and_then(|f| f.get(&id).map(|(m, _)| m.clone()));
            Box::pin(async move { found.ok_or_else(not_found) })
        }

        fn delete(&self, id: String) -> BoxFuture<Result<()>> {
            if let (Ok(mut f), Ok(mut u)) = (self.files.lock(), self.unclaimed.lock()) {
                f.remove(&id);
                u.remove(&id);
            }
            Box::pin(async { Ok(()) })
        }

        fn mark_unclaimed(&self, meta: FileMeta) -> BoxFuture<Result<()>> {
            if let Ok(mut u) = self.unclaimed.lock() {
                u.insert(meta.id, std::time::Instant::now());
            }
            Box::pin(async { Ok(()) })
        }

        fn claim(&self, ids: Vec<String>) -> BoxFuture<Result<()>> {
            if let Ok(mut u) = self.unclaimed.lock() {
                for id in ids {
                    u.remove(&id);
                }
            }
            Box::pin(async { Ok(()) })
        }

        fn unclaimed(
            &self,
            owner: Option<String>,
            tenant: Option<String>,
        ) -> BoxFuture<Result<usize>> {
            let grace = self.grace.unwrap_or(UNCLAIMED_GRACE);
            let count = match (self.files.lock(), self.unclaimed.lock()) {
                (Ok(files), Ok(unclaimed)) => unclaimed
                    .iter()
                    .filter(|(id, since)| {
                        since.elapsed() <= grace
                            && files
                                .get(*id)
                                .is_some_and(|(m, _)| m.owner == owner && m.tenant == tenant)
                    })
                    .count(),
                _ => 0,
            };
            Box::pin(async move { Ok(count) })
        }
    }

    /// Settings of resumable uploads (feature `resumable`), set with
    /// [`App::resumable_uploads`](crate::App::resumable_uploads).
    ///
    /// Parts of unfinished uploads are kept as `{id}.part` files in `dir`; when the last byte
    /// arrives the file goes through the same checks as a plain upload into its store. An upload
    /// with no new bytes for `expires` is removed, and caps limit the open uploads of one user and
    /// of the whole app. Open uploads are known to the process that created them, so several
    /// instances need sticky sessions for these paths.
    ///
    /// ```ignore
    /// App::new("Docs").resumable_uploads(
    ///     ResumableUploads::new("data/uploads")
    ///         .expires(Duration::from_secs(6 * 3600))
    ///         .max_per_user(3),
    /// )
    /// ```
    #[cfg(feature = "resumable")]
    #[derive(Clone, Debug)]
    pub struct ResumableUploads {
        pub(crate) dir: PathBuf,
        pub(crate) expires: std::time::Duration,
        pub(crate) per_user: usize,
        pub(crate) open: usize,
    }

    #[cfg(feature = "resumable")]
    impl Default for ResumableUploads {
        fn default() -> Self {
            ResumableUploads::new(std::env::temp_dir().join("zeyn-uploads"))
        }
    }

    #[cfg(feature = "resumable")]
    impl ResumableUploads {
        /// Unfinished uploads in `dir`, kept 24 hours after their last bytes, at most 5 open
        /// per user and 1000 in all.
        pub fn new(dir: impl Into<PathBuf>) -> Self {
            ResumableUploads {
                dir: dir.into(),
                expires: std::time::Duration::from_secs(24 * 3600),
                per_user: 5,
                open: 1000,
            }
        }

        /// How long an upload with no new bytes is kept.
        pub fn expires(mut self, after: std::time::Duration) -> Self {
            self.expires = after;
            self
        }

        /// Open uploads one user may have; the next creation answers `429`.
        pub fn max_per_user(mut self, n: usize) -> Self {
            self.per_user = n.max(1);
            self
        }

        /// Open uploads of the whole app; the next creation answers `429`.
        pub fn max_open(mut self, n: usize) -> Self {
            self.open = n.max(1);
            self
        }
    }

    /// A new file id: 128 random bits as 32 hex digits.
    pub(crate) fn new_file_id() -> String {
        let mut bytes = [0u8; 16];
        getrandom::getrandom(&mut bytes).expect("the operating system random source must work");
        bytes
            .iter()
            .map(|b| format!("{b:02x}"))
            .collect()
    }
