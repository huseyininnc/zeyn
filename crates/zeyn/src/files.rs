    /// What a store records about a file. The server fills it; the store keeps it with the bytes
    /// and gives it back with [`FileStore::get`] and [`FileStore::meta`].
    #[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
    pub struct FileMeta {
        /// Generated by the server, see [`valid_file_id`].
        pub id: String,
        /// Cleaned name from the client, for display and downloads only.
        pub name: String,
        /// The type found in the content, never the one the client sent.
        pub content_type: String,
        /// Bytes written. The store sets it when the upload ends.
        pub size: u64,
        /// Tenant of the user who uploaded it; downloads from other tenants are refused.
        pub tenant: Option<String>,
        /// User who uploaded it.
        pub owner: Option<String>,
        /// Seconds since 1970 when the upload started.
        pub created: u64,
    }

    impl FileMeta {
        /// The form value for this file.
        pub fn file(&self) -> File {
            File {
                id: self.id.clone(),
                name: self.name.clone(),
                size: self.size,
                content_type: self.content_type.clone(),
            }
        }
    }

    /// The body of an upload, in chunks of at most [`super::UPLOAD_CHUNK`] bytes. An `Err` means
    /// the upload stopped (the client left or a limit was passed): the store must throw away
    /// what it wrote and return an error.
    pub struct FileChunks(pub(crate) tokio::sync::mpsc::Receiver<std::io::Result<Bytes>>);

    impl FileChunks {
        /// The next chunk, `None` at the end.
        pub async fn next(&mut self) -> Option<std::io::Result<Bytes>> {
            self.0.recv().await
        }

        /// [`FileChunks::next`] for code on the blocking pool (`tokio::task::spawn_blocking`).
        pub fn blocking_next(&mut self) -> Option<std::io::Result<Bytes>> {
            self.0.blocking_recv()
        }

        /// Chunks from memory, for tests of a store.
        pub fn from_parts(parts: Vec<Vec<u8>>) -> Self {
            let (tx, rx) = tokio::sync::mpsc::channel(parts.len().max(1));
            for p in parts {
                let _ = tx.try_send(Ok(Bytes::from(p)));
            }
            FileChunks(rx)
        }
    }

    /// A stored file opened for reading.
    pub struct StoredFile {
        pub meta: FileMeta,
        pub reader: Box<dyn MediaReader>,
    }

    /// Where uploaded files are kept. Registered with [`Feature::files`](crate::Feature::files).
    ///
    /// Ids reaching a store have passed [`valid_file_id`]; a store never builds a path from
    /// anything else. Unknown ids are [`Error::NotFound`].
    pub trait FileStore: Send + Sync + 'static {
        /// Writes a new file. `meta.size` is 0; the store records the bytes it wrote. On an
        /// `Err` chunk the store removes what it wrote and fails.
        fn put(&self, meta: FileMeta, chunks: FileChunks) -> BoxFuture<Result<()>>;

        /// Opens a file for reading, with its metadata.
        fn get(&self, id: String) -> BoxFuture<Result<StoredFile>>;

        /// The metadata of a file.
        fn meta(&self, id: String) -> BoxFuture<Result<FileMeta>>;

        /// Removes a file. Removing an unknown id is not an error.
        fn delete(&self, id: String) -> BoxFuture<Result<()>>;

        /// Records that the file `meta` names, just uploaded, waits for a saved record to claim
        /// it with [`FileStore::claim`]; a store set to expire unclaimed uploads may remove it
        /// once its grace period passes unclaimed. Files written with [`FileStore::put`] alone
        /// count as claimed. The default does nothing, so a store that does not track claims
        /// never removes a file.
        fn mark_unclaimed(&self, meta: FileMeta) -> BoxFuture<Result<()>> {
            let _ = meta;
            Box::pin(async { Ok(()) })
        }

        /// Marks files as claimed by a saved record, so they are kept. Unknown or already
        /// claimed ids are not an error.
        fn claim(&self, ids: Vec<String>) -> BoxFuture<Result<()>> {
            let _ = ids;
            Box::pin(async { Ok(()) })
        }

        /// How many uploads of `owner` (`None` for uploads without a signed in user) in `tenant`
        /// are unclaimed and younger than the grace period, for [`FileRules::max_unclaimed`].
        /// The default, for stores that do not track claims, is 0.
        fn unclaimed(
            &self,
            owner: Option<String>,
            tenant: Option<String>,
        ) -> BoxFuture<Result<usize>> {
            let _ = (owner, tenant);
            Box::pin(async { Ok(0) })
        }
    }

    /// How long unclaimed uploads of a [`DiskStore`] or a [`MemoryStore`] count against
    /// [`FileRules::max_unclaimed`] when the store does not remove them (no `unclaimed_for`).
    pub const UNCLAIMED_GRACE: std::time::Duration = std::time::Duration::from_secs(24 * 3600);

    /// Whether a scanned file may be kept.
    #[derive(Clone, Debug, PartialEq, Eq)]
    pub enum ScanVerdict {
        Clean,
        /// Refused, with the reason for the log. The user sees a general message.
        Refused(String),
    }

    /// Checks an uploaded file before it is accepted, such as a virus scanner. Registered with
    /// [`Feature::scan_files`](crate::Feature::scan_files). A refused file, or a scanner that
    /// fails, is deleted and the upload answers `422`.
    pub trait FileScanner: Send + Sync + 'static {
        fn scan(
            &self,
            meta: FileMeta,
            file: Box<dyn MediaReader>,
        ) -> BoxFuture<Result<ScanVerdict>>;
    }

    /// Refuses ZIP based uploads (ZIP, Word, Excel, PowerPoint) that would unpack into far more
    /// than they weigh, before anything opens them: more entries than `max_entries`, more than
    /// `max_bytes` in all, or more than `max_ratio` times the file's own size, as the archive's
    /// central directory declares them. ZIP64 archives are refused, since their sizes are not
    /// checked. Code that unpacks an accepted archive must still stop at these limits, because a
    /// directory can understate what an entry holds. Register it with
    /// [`Feature::scan_files`](crate::Feature::scan_files); other files pass.
    ///
    /// ```ignore
    /// Feature::new("imports").files(SHEETS, "imports.write", store).scan_files(ZipGuard::default())
    /// ```
    #[derive(Clone, Copy, Debug, PartialEq, Eq)]
    pub struct ZipGuard {
        pub max_entries: u64,
        pub max_bytes: u64,
        pub max_ratio: u64,
    }

    impl Default for ZipGuard {
        fn default() -> Self {
            ZipGuard {
                max_entries: 10_000,
                max_bytes: 1024 * 1024 * 1024,
                max_ratio: 200,
            }
        }
    }

    /// Largest central directory read, so the check itself stays small.
    const ZIP_DIRECTORY_MAX: u64 = 64 * 1024 * 1024;

    /// The number of entries and the sum of their unpacked sizes, from the central directory.
    fn zip_totals(r: &mut dyn MediaReader) -> std::result::Result<(u64, u64), &'static str> {
        use std::io::SeekFrom;
        let len = r
            .seek(SeekFrom::End(0))
            .map_err(|_| "unreadable")?;
        let tail = len.min(65_557);
        r.seek(SeekFrom::Start(len - tail))
            .map_err(|_| "unreadable")?;
        let mut end = vec![0u8; tail as usize];
        r.read_exact(&mut end)
            .map_err(|_| "unreadable")?;
        let at = (0..end.len().saturating_sub(21))
            .rev()
            .find(|&i| end[i..i + 4] == [0x50, 0x4b, 0x05, 0x06])
            .ok_or("no central directory")?;
        let u16_at = |b: &[u8], i: usize| u64::from(u16::from_le_bytes([b[i], b[i + 1]]));
        let u32_at = |b: &[u8], i: usize| {
            u64::from(u32::from_le_bytes([b[i], b[i + 1], b[i + 2], b[i + 3]]))
        };
        let entries = u16_at(&end, at + 10);
        let size = u32_at(&end, at + 12);
        let offset = u32_at(&end, at + 16);
        if entries == 0xFFFF || size == 0xFFFF_FFFF || offset == 0xFFFF_FFFF {
            return Err("ZIP64 archive");
        }
        if size > ZIP_DIRECTORY_MAX || offset + size > len {
            return Err("central directory out of range");
        }
        r.seek(SeekFrom::Start(offset))
            .map_err(|_| "unreadable")?;
        let mut dir = vec![0u8; size as usize];
        r.read_exact(&mut dir)
            .map_err(|_| "unreadable")?;
        let (mut i, mut count, mut total) = (0usize, 0u64, 0u64);
        while i + 46 <= dir.len() && dir[i..i + 4] == [0x50, 0x4b, 0x01, 0x02] {
            let unpacked = u32_at(&dir, i + 24);
            if unpacked == 0xFFFF_FFFF {
                return Err("ZIP64 entry");
            }
            total = total.saturating_add(unpacked);
            count += 1;
            let skip = u16_at(&dir, i + 28) + u16_at(&dir, i + 30) + u16_at(&dir, i + 32);
            i += 46 + skip as usize;
        }
        Ok((count.max(entries), total))
    }

    impl FileScanner for ZipGuard {
        fn scan(
            &self,
            meta: FileMeta,
            mut file: Box<dyn MediaReader>,
        ) -> BoxFuture<Result<ScanVerdict>> {
            let zipped = [
                FileType::Zip,
                FileType::Docx,
                FileType::Xlsx,
                FileType::Pptx,
            ]
            .iter()
            .any(|t| t.mime() == meta.content_type);
            let guard = *self;
            Box::pin(async move {
                if !zipped {
                    return Ok(ScanVerdict::Clean);
                }
                let totals = tokio::task::spawn_blocking(move || zip_totals(&mut *file))
                    .await
                    .map_err(|e| Error::Internal(e.to_string()))?;
                let verdict = match totals {
                    Err(why) => ScanVerdict::Refused(format!("zip: {why}")),
                    Ok((entries, _)) if entries > guard.max_entries => {
                        ScanVerdict::Refused(format!("zip: {entries} entries"))
                    }
                    Ok((_, total)) if total > guard.max_bytes => {
                        ScanVerdict::Refused(format!("zip: unpacks to {total} bytes"))
                    }
                    Ok((_, total)) if total / meta.size.max(1) > guard.max_ratio => {
                        ScanVerdict::Refused(format!(
                            "zip: unpacks to {total} bytes from {}",
                            meta.size
                        ))
                    }
                    Ok(_) => ScanVerdict::Clean,
                };
                Ok(verdict)
            })
        }
    }

    /// The file stores of a running app by name. The server keeps it as a service on every
    /// request, so a form or a drop zone can check the file ids the browser names.
    #[derive(Clone, Default)]
    pub(crate) struct FileStores(pub(crate) Arc<HashMap<&'static str, Arc<dyn FileStore>>>);

    impl crate::ctx::Service for FileStores {}

    /// Refuses with [`Error::NotFound`] when `store` (any store of the app when `None`) does
    /// not hold every file of `ids` for the user of `ctx`: a file another user uploaded, one of
    /// another tenant, or an id never uploaded. Uploads without a signed in user have no owner,
    /// so a request without one may name only such uploads, by ids of 128 random bits nobody
    /// else learns.
    pub(crate) async fn check_owned(
        ctx: &crate::Ctx,
        store: Option<&str>,
        ids: Vec<String>,
    ) -> Result<()> {
        if ids.is_empty() {
            return Ok(());
        }
        let stores = stores_of(ctx, store);
        let user = ctx.identity().user.as_deref();
        let tenant = ctx.tenant().map(|t| t.id());
        for id in ids {
            let mut found = false;
            for store in &stores {
                if let Ok(meta) = store.meta(id.clone()).await {
                    found = meta.id == id
                        && meta.owner.as_deref() == user
                        && meta.tenant.as_deref() == tenant;
                    if found {
                        break;
                    }
                }
            }
            if !found {
                return Err(Error::NotFound);
            }
        }
        Ok(())
    }

    /// The store named `store` of the app, or every store when `None`.
    fn stores_of(ctx: &crate::Ctx, store: Option<&str>) -> Vec<Arc<dyn FileStore>> {
        let all = ctx
            .service::<FileStores>()
            .unwrap_or_default();
        match store {
            Some(name) => all
                .0
                .get(name)
                .cloned()
                .into_iter()
                .collect(),
            None => all.0.values().cloned().collect(),
        }
    }

    /// Claims `ids` in `store` (every store of the app when `None`) after a record that holds
    /// them was saved, so the store keeps them past its grace period. A store that fails is
    /// logged; the save already happened.
    pub(crate) async fn claim(ctx: &crate::Ctx, store: Option<&str>, ids: Vec<String>) {
        if ids.is_empty() {
            return;
        }
        for s in stores_of(ctx, store) {
            if let Err(e) = s.claim(ids.clone()).await {
                tracing::warn!(error = ?e, "saved files could not be claimed; the store may remove them after its grace period");
            }
        }
    }

