    use std::path::PathBuf;
    use std::sync::{Arc, Mutex};

    /// What a store records about a file. The server fills it; the store keeps it with the bytes
    /// and gives it back with [`FileStore::get`] and [`FileStore::meta`].
    #[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
    pub struct FileMeta {
        /// Generated by the server, see [`valid_file_id`].
        pub id: String,
        /// Cleaned name from the client, for display and downloads only.
        pub name: String,
        /// The type found in the content, never the one the client sent.
        pub content_type: String,
        /// Bytes written. The store sets it when the upload ends.
        pub size: u64,
        /// Tenant of the user who uploaded it; downloads from other tenants are refused.
        pub tenant: Option<String>,
        /// User who uploaded it.
        pub owner: Option<String>,
        /// Seconds since 1970 when the upload started.
        pub created: u64,
    }

    impl FileMeta {
        /// The form value for this file.
        pub fn file(&self) -> File {
            File {
                id: self.id.clone(),
                name: self.name.clone(),
                size: self.size,
                content_type: self.content_type.clone(),
            }
        }
    }

    /// The body of an upload, in chunks of at most [`super::UPLOAD_CHUNK`] bytes. An `Err` means
    /// the upload stopped (the client left or a limit was passed): the store must throw away
    /// what it wrote and return an error.
    pub struct FileChunks(pub(crate) tokio::sync::mpsc::Receiver<std::io::Result<Bytes>>);

    impl FileChunks {
        /// The next chunk, `None` at the end.
        pub async fn next(&mut self) -> Option<std::io::Result<Bytes>> {
            self.0.recv().await
        }

        /// [`FileChunks::next`] for code on the blocking pool (`tokio::task::spawn_blocking`).
        pub fn blocking_next(&mut self) -> Option<std::io::Result<Bytes>> {
            self.0.blocking_recv()
        }

        /// Chunks from memory, for tests of a store.
        pub fn from_parts(parts: Vec<Vec<u8>>) -> Self {
            let (tx, rx) = tokio::sync::mpsc::channel(parts.len().max(1));
            for p in parts {
                let _ = tx.try_send(Ok(Bytes::from(p)));
            }
            FileChunks(rx)
        }
    }

    /// A stored file opened for reading.
    pub struct StoredFile {
        pub meta: FileMeta,
        pub reader: Box<dyn MediaReader>,
    }

    /// Where uploaded files are kept. Registered with [`Feature::files`](crate::Feature::files).
    ///
    /// Ids reaching a store have passed [`valid_file_id`]; a store never builds a path from
    /// anything else. Unknown ids are [`Error::NotFound`].
    pub trait FileStore: Send + Sync + 'static {
        /// Writes a new file. `meta.size` is 0; the store records the bytes it wrote. On an
        /// `Err` chunk the store removes what it wrote and fails.
        fn put(&self, meta: FileMeta, chunks: FileChunks) -> BoxFuture<Result<()>>;

        /// Opens a file for reading, with its metadata.
        fn get(&self, id: String) -> BoxFuture<Result<StoredFile>>;

        /// The metadata of a file.
        fn meta(&self, id: String) -> BoxFuture<Result<FileMeta>>;

        /// Removes a file. Removing an unknown id is not an error.
        fn delete(&self, id: String) -> BoxFuture<Result<()>>;
    }

    /// Whether a scanned file may be kept.
    #[derive(Clone, Debug, PartialEq, Eq)]
    pub enum ScanVerdict {
        Clean,
        /// Refused, with the reason for the log. The user sees a general message.
        Refused(String),
    }

    /// Checks an uploaded file before it is accepted, such as a virus scanner. Registered with
    /// [`Feature::scan_files`](crate::Feature::scan_files). A refused file, or a scanner that
    /// fails, is deleted and the upload answers `422`.
    pub trait FileScanner: Send + Sync + 'static {
        fn scan(
            &self,
            meta: FileMeta,
            file: Box<dyn MediaReader>,
        ) -> BoxFuture<Result<ScanVerdict>>;
    }

    /// A store registered on a feature.
    #[derive(Clone)]
    pub struct FileEntry {
        pub rules: FileRules,
        pub permission: &'static str,
        pub store: Arc<dyn FileStore>,
    }

    fn not_found() -> Error {
        Error::NotFound
    }

    fn io(e: std::io::Error) -> Error {
        Error::Internal(format!("file store: {e}"))
    }

    /// Files on the local disk under one folder: `{id}.bin` holds the bytes and `{id}.json` the
    /// metadata. Uploads are written to `{id}.part` and renamed when complete, so a stopped
    /// upload never shows up. Writing happens on the blocking pool, one chunk at a time.
    #[derive(Clone)]
    pub struct DiskStore {
        root: Arc<PathBuf>,
    }

    impl DiskStore {
        /// A store in `root`, created on the first upload.
        pub fn new(root: impl Into<PathBuf>) -> Self {
            DiskStore {
                root: Arc::new(root.into()),
            }
        }

        fn path(&self, id: &str, ext: &str) -> Result<PathBuf> {
            if !valid_file_id(id) {
                return Err(not_found());
            }
            Ok(self.root.join(format!("{id}.{ext}")))
        }
    }

    impl FileStore for DiskStore {
        fn put(&self, mut meta: FileMeta, mut chunks: FileChunks) -> BoxFuture<Result<()>> {
            let paths = (
                self.path(&meta.id, "part"),
                self.path(&meta.id, "bin"),
                self.path(&meta.id, "json"),
            );
            let root = self.root.clone();
            Box::pin(async move {
                let (part, bin, json) = (paths.0?, paths.1?, paths.2?);
                let work = tokio::task::spawn_blocking(move || {
                    std::fs::create_dir_all(&*root).map_err(io)?;
                    let mut file = std::fs::File::create_new(&part).map_err(io)?;
                    let written = (|| {
                        let mut size = 0u64;
                        while let Some(chunk) = chunks.blocking_next() {
                            let chunk = chunk.map_err(io)?;
                            file.write_all(&chunk).map_err(io)?;
                            size += chunk.len() as u64;
                        }
                        file.sync_all().map_err(io)?;
                        Ok::<_, Error>(size)
                    })();
                    drop(file);
                    let size = match written {
                        Ok(size) => size,
                        Err(e) => {
                            let _ = std::fs::remove_file(&part);
                            return Err(e);
                        }
                    };
                    meta.size = size;
                    let text =
                        serde_json::to_vec(&meta).map_err(|e| Error::Internal(e.to_string()))?;
                    std::fs::write(&json, text).map_err(io)?;
                    std::fs::rename(&part, &bin).map_err(io)
                });
                work.await
                    .map_err(|e| Error::Internal(e.to_string()))?
            })
        }

        fn get(&self, id: String) -> BoxFuture<Result<StoredFile>> {
            let paths = (self.path(&id, "bin"), self.path(&id, "json"));
            Box::pin(async move {
                let (bin, json) = (paths.0?, paths.1?);
                tokio::task::spawn_blocking(move || {
                    let meta: FileMeta = read_meta(&json)?;
                    let file = std::fs::File::open(&bin).map_err(|_| not_found())?;
                    Ok(StoredFile {
                        meta,
                        reader: Box::new(file),
                    })
                })
                .await
                .map_err(|e| Error::Internal(e.to_string()))?
            })
        }

        fn meta(&self, id: String) -> BoxFuture<Result<FileMeta>> {
            let json = self.path(&id, "json");
            Box::pin(async move {
                let json = json?;
                tokio::task::spawn_blocking(move || read_meta(&json))
                    .await
                    .map_err(|e| Error::Internal(e.to_string()))?
            })
        }

        fn delete(&self, id: String) -> BoxFuture<Result<()>> {
            let paths = (self.path(&id, "bin"), self.path(&id, "json"));
            Box::pin(async move {
                let (bin, json) = (paths.0?, paths.1?);
                tokio::task::spawn_blocking(move || {
                    for p in [bin, json] {
                        match std::fs::remove_file(&p) {
                            Ok(()) => {}
                            Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
                            Err(e) => return Err(io(e)),
                        }
                    }
                    Ok(())
                })
                .await
                .map_err(|e| Error::Internal(e.to_string()))?
            })
        }
    }

    fn read_meta(path: &std::path::Path) -> Result<FileMeta> {
        let text = std::fs::read(path).map_err(|_| not_found())?;
        serde_json::from_slice(&text).map_err(|e| Error::Internal(e.to_string()))
    }

    type Held = HashMap<String, (FileMeta, Arc<[u8]>)>;

    /// Files in memory, for tests and demos. Capped by total bytes; an upload that would pass
    /// the cap is refused. Unlike [`DiskStore`] it holds every file whole.
    #[derive(Clone)]
    pub struct MemoryStore {
        files: Arc<Mutex<Held>>,
        cap: u64,
    }

    impl Default for MemoryStore {
        fn default() -> Self {
            MemoryStore::new(64 * 1024 * 1024)
        }
    }

    impl MemoryStore {
        /// A store that holds at most `cap` bytes in all.
        pub fn new(cap: u64) -> Self {
            MemoryStore {
                files: Arc::new(Mutex::new(HashMap::new())),
                cap,
            }
        }

        /// Ids of the stored files, for tests.
        pub fn ids(&self) -> Vec<String> {
            self.files
                .lock()
                .map(|f| f.keys().cloned().collect())
                .unwrap_or_default()
        }

        fn used(&self) -> u64 {
            self.files
                .lock()
                .map(|f| f.values().map(|(m, _)| m.size).sum())
                .unwrap_or(0)
        }
    }

    impl FileStore for MemoryStore {
        fn put(&self, mut meta: FileMeta, mut chunks: FileChunks) -> BoxFuture<Result<()>> {
            let this = self.clone();
            Box::pin(async move {
                let room = this.cap.saturating_sub(this.used());
                let mut data = Vec::new();
                while let Some(chunk) = chunks.next().await {
                    let chunk = chunk.map_err(io)?;
                    if (data.len() + chunk.len()) as u64 > room {
                        return Err(Error::Denied(Text::key("zeyn.files.store_full")));
                    }
                    data.extend_from_slice(&chunk);
                }
                meta.size = data.len() as u64;
                let mut files = this
                    .files
                    .lock()
                    .map_err(|_| Error::Internal("file store lock".into()))?;
                files.insert(meta.id.clone(), (meta, data.into()));
                Ok(())
            })
        }

        fn get(&self, id: String) -> BoxFuture<Result<StoredFile>> {
            let found = self
                .files
                .lock()
                .ok()
                .and_then(|f| f.get(&id).cloned());
            Box::pin(async move {
                let (meta, data) = found.ok_or_else(not_found)?;
                Ok(StoredFile {
                    meta,
                    reader: Box::new(Cursor::new(data)),
                })
            })
        }

        fn meta(&self, id: String) -> BoxFuture<Result<FileMeta>> {
            let found = self
                .files
                .lock()
                .ok()
                .and_then(|f| f.get(&id).map(|(m, _)| m.clone()));
            Box::pin(async move { found.ok_or_else(not_found) })
        }

        fn delete(&self, id: String) -> BoxFuture<Result<()>> {
            if let Ok(mut f) = self.files.lock() {
                f.remove(&id);
            }
            Box::pin(async { Ok(()) })
        }
    }

    /// A new file id: 128 random bits as 32 hex digits.
    pub(crate) fn new_file_id() -> String {
        let mut bytes = [0u8; 16];
        getrandom::getrandom(&mut bytes).expect("the operating system random source must work");
        bytes
            .iter()
            .map(|b| format!("{b:02x}"))
            .collect()
    }
