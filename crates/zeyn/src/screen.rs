/// Screen params. Implemented by `#[params]`; screens without params use `()`.
#[diagnostic::on_unimplemented(
    message = "`{Self}` is not a screen params type",
    label = "the first argument of a screen is its params",
    note = "mark the type with `#[params]`, or use `_: ()` as the first argument when the screen has no params"
)]
pub trait Params: Serialize + DeserializeOwned + Clone + Send + Sync + 'static {}

impl Params for () {}

/// Screen definition generated by `#[screen]`.
#[derive(Clone, Copy, Debug, Serialize)]
pub struct ScreenMeta {
    pub name: &'static str,
    pub route: Option<&'static str>,
    pub access: Access,
}

/// A screen. Implemented by `#[screen]`, never written by hand.
pub trait ScreenDef: Copy + Send + Sync + 'static {
    type Params: Params;
    const META: ScreenMeta;

    /// Services the screen needs; checked when the app starts.
    fn deps() -> Vec<Dep>;

    /// Builds the screen with injected arguments. Access is checked by the caller.
    fn build(ctx: Ctx, params: Self::Params) -> BoxFuture<Result<Screen>>;
}

/// What the client does after a user interaction.
#[derive(Clone, Debug, PartialEq, Serialize)]
#[serde(tag = "effect", rename_all = "snake_case")]
pub enum Effect {
    OpenWindow { screen: &'static str, params: serde_json::Value },
    Navigate { screen: &'static str, params: serde_json::Value },
    Toast { message: Text },
    CloseAndRefresh,
}

impl Effect {
    /// JSON sent to the client, with texts resolved in the user's language.
    pub fn to_json(&self, r: &Render) -> serde_json::Value {
        match self {
            Effect::Toast { message } => {
                json!({ "effect": "toast", "message": r.i18n.text(r.locale, message) })
            }
            other => serde_json::to_value(other).unwrap_or(serde_json::Value::Null),
        }
    }
}

/// Serializes params. Cannot fail for types marked with `#[params]`.
fn params_json<P: Params>(params: &P) -> serde_json::Value {
    serde_json::to_value(params).expect("screen params must serialize to JSON")
}

/// Window helpers.
pub struct Window;

impl Window {
    /// Effect that opens a screen as a window. Params of the wrong type do not compile.
    pub fn open<S: ScreenDef>(_screen: S, params: S::Params) -> Effect {
        Effect::OpenWindow { screen: S::META.name, params: params_json(&params) }
    }
}

/// Context given to event handlers. Collects the effects they ask for.
#[derive(Debug, Default)]
pub struct UiCtx {
    effects: Vec<Effect>,
}

impl UiCtx {
    pub fn toast(&mut self, message: impl Into<Text>) {
        self.effects.push(Effect::Toast { message: message.into() });
    }

    /// Closes the window and refreshes the screen that opened it.
    pub fn close_and_refresh(&mut self) {
        self.effects.push(Effect::CloseAndRefresh);
    }

    pub fn navigate<S: ScreenDef>(&mut self, _screen: S, params: S::Params) {
        self.effects.push(Effect::Navigate { screen: S::META.name, params: params_json(&params) });
    }

    pub fn into_effects(self) -> Vec<Effect> {
        self.effects
    }
}

/// One loaded page of grid rows, type erased.
pub struct LoadedPage {
    pub items: Box<dyn Any + Send>,
    pub count: usize,
    pub total: Option<u64>,
    pub next: Option<Cursor>,
    pub offset: u64,
    /// Column totals over the whole filtered result.
    pub totals: Vec<crate::action::Total>,
    /// Column layout the rows are rendered in; `None` is the grid's own layout.
    pub view: Option<crate::grid::DataGridView>,
    /// Whether the user's view changes are saved on the server.
    pub saved_views: bool,
}

/// A component that loads rows through an action. Implemented by `Grid`.
pub trait GridSource: Send + Sync {
    fn action(&self) -> ActionMeta;

    /// Query for the first page, as the grid's paging asks for it, with the sort and filters of
    /// a saved view.
    fn first_query(&self, view: Option<&crate::grid::DataGridView>) -> GridQuery;

    /// Cleans a view sent by a client so only the grid's own columns, sort keys and filters remain.
    fn clean_view(&self, view: crate::grid::DataGridView) -> crate::grid::DataGridView;

    /// Header row for a view.
    fn head_html(&self, r: &Render, view: Option<&crate::grid::DataGridView>) -> String;

    fn fetch(&self, ctx: Ctx, query: GridQuery) -> BoxFuture<Result<LoadedPage>>;

    /// Rows of a loaded page as HTML.
    fn rows_html(&self, page: &LoadedPage, r: &Render) -> String;

    /// Footer row with the totals of a loaded page, or `None` when the grid has no totals or the
    /// page carries none (the client keeps the footer it has).
    fn foot_html(&self, page: &LoadedPage, r: &Render) -> Option<String>;

    /// Renders the grid with its first page already in place.
    fn render_loaded(&self, out: &mut String, r: &Render, page: &LoadedPage);

    /// JSON Schema of the query, for agent tools.
    fn tool_schema(&self) -> serde_json::Value;
}

/// A component that saves data through an action. Implemented by forms with `submit`.
pub trait FormSource: Send + Sync {
    fn action(&self) -> ActionMeta;

    /// Parses submitted values, validates and runs the action. `values` holds what the user typed.
    fn submit(&self, ctx: Ctx, values: serde_json::Map<String, serde_json::Value>) -> BoxFuture<Result<Vec<Effect>>>;

    /// JSON Schema of the values, for agent tools.
    fn tool_schema(&self) -> serde_json::Value;
}

/// Anything that can be placed on a screen. This is the extension point for third party components.
///
/// A component writes its own HTML and describes itself in the schema. It must escape user data
/// with [`crate::render::escape`] (or [`Render::text`] and [`Render::value`]) and give interactive
/// parts a `data-testid` that starts with `r.scope`.
pub trait Component: Send + Sync {
    fn render(&self, out: &mut String, r: &Render);

    /// Schema used by MCP tools and test generation. Include a `"type"` key.
    fn schema(&self) -> serde_json::Value;

    fn grid(&self) -> Option<&dyn GridSource> {
        None
    }

    fn form(&self) -> Option<&dyn FormSource> {
        None
    }

    /// Nodes held by a container. Child `i` of the node at path `p` has the path `p.i`.
    fn children(&self) -> &[Node] {
        &[]
    }

    /// Children rendered with the page. Others, such as closed lazy tabs, load when first shown.
    fn eager_children(&self) -> &[Node] {
        self.children()
    }

    /// Data the component fetches through an action, by key (a field name for lookups).
    fn source(&self, _key: &str) -> Option<&dyn crate::ui::DataSource> {
        None
    }
}

/// Type erased component: a node of the screen tree.
pub struct Node(Box<dyn Component>);

impl Node {
    pub fn new(component: impl Component + 'static) -> Self {
        Self(Box::new(component))
    }

    pub fn render(&self, out: &mut String, r: &Render) {
        self.0.render(out, r);
    }

    pub fn schema(&self) -> serde_json::Value {
        self.0.schema()
    }

    pub fn grid(&self) -> Option<&dyn GridSource> {
        self.0.grid()
    }

    pub fn form(&self) -> Option<&dyn FormSource> {
        self.0.form()
    }

    pub fn children(&self) -> &[Node] {
        self.0.children()
    }

    pub fn eager_children(&self) -> &[Node] {
        self.0.eager_children()
    }

    pub fn source(&self, key: &str) -> Option<&dyn crate::ui::DataSource> {
        self.0.source(key)
    }
}

/// Icons.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum Icon {
    Plus,
    Edit,
    Delete,
    Save,
    Search,
    Box,
    Cart,
    Table,
    Home,
    Chart,
}

impl Icon {
    fn css(self) -> &'static str {
        match self {
            Icon::Plus => "plus",
            Icon::Edit => "edit",
            Icon::Delete => "delete",
            Icon::Save => "save",
            Icon::Search => "search",
            Icon::Box => "box",
            Icon::Cart => "cart",
            Icon::Table => "table",
            Icon::Home => "home",
            Icon::Chart => "chart",
        }
    }

    /// Icon markup, hidden from screen readers.
    pub fn html(self) -> String {
        format!(r#"<span class="z-icon z-icon-{}" aria-hidden="true"></span>"#, self.css())
    }
}

/// Export format.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum Export {
    Xlsx,
    Csv,
}

impl Export {
    fn code(self) -> &'static str {
        match self {
            Export::Xlsx => "xlsx",
            Export::Csv => "csv",
        }
    }
}

#[derive(Debug)]
struct ButtonSpec {
    label: Text,
    icon: Option<Icon>,
    shortcut: Option<String>,
    effect: Option<Effect>,
}

#[derive(Debug)]
enum ToolItem {
    Button(ButtonSpec),
    Export(Export),
}

/// Screen toolbar.
#[derive(Debug, Default)]
pub struct Toolbar {
    items: Vec<ToolItem>,
}

impl Toolbar {
    pub fn button(self, label: impl Into<Text>) -> ToolButton {
        ToolButton { bar: self, spec: ButtonSpec { label: label.into(), icon: None, shortcut: None, effect: None } }
    }

    /// Export button for the grid on this screen.
    pub fn export(mut self, format: Export) -> Toolbar {
        self.items.push(ToolItem::Export(format));
        self
    }

    pub(crate) fn render(&self, out: &mut String, r: &Render, title: &str) {
        let scope = r.scope;
        out.push_str(&format!(r#"<div class="z-toolbar" role="toolbar" aria-label="{title}">"#));
        for item in &self.items {
            match item {
                ToolItem::Button(b) => {
                    let english = b.label.english();
                    out.push_str(&format!(
                        r#"<button type="button" class="z-button" data-testid="{scope}.toolbar.{}""#,
                        slug(&english)
                    ));
                    if let Some(s) = &b.shortcut {
                        out.push_str(&format!(r#" aria-keyshortcuts="{}""#, crate::render::escape(&s.replace("Ctrl", "Control"))));
                    }
                    if let Some(e) = &b.effect {
                        out.push_str(&format!(r#" data-zeyn-effect="{}""#, attr(e)));
                    }
                    out.push('>');
                    if let Some(i) = b.icon {
                        out.push_str(&i.html());
                    }
                    out.push_str(&r.text(&b.label));
                    out.push_str("</button>");
                }
                ToolItem::Export(e) => out.push_str(&format!(
                    r#"<button type="button" class="z-button" data-testid="{scope}.toolbar.export-{code}" data-zeyn-export="{code}">{}</button>"#,
                    r.text(&Text::key(format!("zeyn.export.{}", e.code()))),
                    code = e.code()
                )),
            }
        }
        out.push_str("</div>");
    }

    pub(crate) fn schema(&self) -> serde_json::Value {
        self.items
            .iter()
            .map(|item| match item {
                ToolItem::Button(b) => json!({
                    "type": "button",
                    "label": b.label,
                    "icon": b.icon,
                    "shortcut": b.shortcut,
                    "effect": b.effect,
                }),
                ToolItem::Export(e) => json!({ "type": "export", "format": e }),
            })
            .collect()
    }
}

/// Toolbar button being configured.
pub struct ToolButton {
    bar: Toolbar,
    spec: ButtonSpec,
}

impl ToolButton {
    pub fn icon(mut self, icon: Icon) -> Self {
        self.spec.icon = Some(icon);
        self
    }

    /// Keyboard shortcut such as `"Ctrl+N"`.
    pub fn shortcut(mut self, keys: impl Into<String>) -> Self {
        self.spec.shortcut = Some(keys.into());
        self
    }

    /// Opens the screen as a window when the button is pressed.
    pub fn opens<S: ScreenDef>(mut self, screen: S, params: S::Params) -> Self {
        self.spec.effect = Some(Window::open(screen, params));
        self
    }

    pub fn button(self, label: impl Into<Text>) -> ToolButton {
        self.finish().button(label)
    }

    pub fn export(self, format: Export) -> Toolbar {
        self.finish().export(format)
    }

    fn finish(mut self) -> Toolbar {
        self.bar.items.push(ToolItem::Button(self.spec));
        self.bar
    }
}

impl From<ToolButton> for Toolbar {
    fn from(b: ToolButton) -> Self {
        b.finish()
    }
}

#[derive(Clone, Copy, Debug)]
enum ScreenKind {
    Page,
    Window { width: u32 },
}

/// Content of a screen. Screen functions return this.
pub struct Screen {
    title: Text,
    kind: ScreenKind,
    toolbar: Option<Toolbar>,
    body: Vec<Node>,
}

impl Screen {
    /// Full page screen.
    pub fn new(title: impl Into<Text>) -> Self {
        Self { title: title.into(), kind: ScreenKind::Page, toolbar: None, body: Vec::new() }
    }

    /// Screen opened as a window.
    pub fn window(title: impl Into<Text>) -> Self {
        Self { kind: ScreenKind::Window { width: 560 }, ..Self::new(title) }
    }

    /// Window width in pixels. No effect on full page screens.
    pub fn width(mut self, px: u32) -> Self {
        if let ScreenKind::Window { width } = &mut self.kind {
            *width = px;
        }
        self
    }

    pub fn toolbar<F, R>(mut self, build: F) -> Self
    where
        F: FnOnce(Toolbar) -> R,
        R: Into<Toolbar>,
    {
        self.toolbar = Some(build(Toolbar::default()).into());
        self
    }

    pub fn body(mut self, node: impl Into<Node>) -> Self {
        self.body.push(node.into());
        self
    }

    pub fn title(&self) -> &Text {
        &self.title
    }

    pub fn nodes(&self) -> &[Node] {
        &self.body
    }

    /// Renders the screen in English with no params and no preloaded rows. For tests and tools.
    pub fn html(&self, meta: &ScreenMeta) -> String {
        self.render(&Render::english(meta.name), meta, &serde_json::Value::Null, &HashMap::new())
    }

    /// Renders the screen. `loaded` holds the first page of grids by node path (`"0"`, `"1.2"`).
    pub fn render(
        &self,
        r: &Render,
        meta: &ScreenMeta,
        params: &serde_json::Value,
        loaded: &HashMap<String, LoadedPage>,
    ) -> String {
        let scope = meta.name;
        let r = Render { scope, loaded: Some(loaded), ..*r };
        let title = r.text(&self.title);
        let params = attr(params);
        let mut out = String::new();
        let close = match self.kind {
            ScreenKind::Page => {
                out.push_str(&format!(
                    r#"<section class="z-screen" data-zeyn-screen="{scope}" data-zeyn-params="{params}" aria-labelledby="{scope}-title"><h1 id="{scope}-title">{title}</h1>"#
                ));
                "</section>"
            }
            ScreenKind::Window { width } => {
                out.push_str(&format!(
                    r#"<div class="z-window" role="dialog" aria-modal="true" data-zeyn-screen="{scope}" data-zeyn-params="{params}" aria-labelledby="{scope}-title" style="--z-width:{width}px"><h2 id="{scope}-title">{title}</h2>"#
                ));
                "</div>"
            }
        };
        if let Some(t) = &self.toolbar {
            t.render(&mut out, &r, &title);
        }
        for (i, node) in self.body.iter().enumerate() {
            crate::ui::render_node(&mut out, &r, &i.to_string(), node);
        }
        out.push_str(close);
        out
    }

    /// Screen schema used by MCP tools, test generation and validation.
    pub fn schema(&self, meta: &ScreenMeta) -> serde_json::Value {
        let (kind, width) = match self.kind {
            ScreenKind::Page => ("page", None),
            ScreenKind::Window { width } => ("window", Some(width)),
        };
        json!({
            "screen": meta,
            "title": self.title,
            "kind": kind,
            "width": width,
            "toolbar": self.toolbar.as_ref().map(Toolbar::schema),
            "body": self.body.iter().map(Node::schema).collect::<Vec<_>>(),
        })
    }
}
