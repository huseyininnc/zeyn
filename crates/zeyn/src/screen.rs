#[derive(Debug)]
struct ButtonSpec {
    label: Text,
    icon: Option<Icon>,
    shortcut: Option<String>,
    override_browser: bool,
    effect: Option<Effect>,
    tip: Option<Text>,
}

#[derive(Debug)]
#[allow(
    clippy::large_enum_variant,
    reason = "nearly every entry of the list is the large variant, so boxing it would add an allocation per entry and save no memory"
)]
enum ToolItem {
    Button(ButtonSpec),
    Export(Export),
}

/// Screen toolbar.
#[derive(Debug, Default)]
pub struct Toolbar {
    items: Vec<ToolItem>,
}

impl Toolbar {
    pub fn button(self, label: impl Into<Text>) -> ToolButton {
        ToolButton {
            bar: self,
            spec: ButtonSpec {
                label: label.into(),
                icon: None,
                shortcut: None,
                override_browser: false,
                effect: None,
                tip: None,
            },
        }
    }

    /// Export button for the grid on this screen.
    pub fn export(mut self, format: Export) -> Toolbar {
        self.items
            .push(ToolItem::Export(format));
        self
    }

    pub(crate) fn render(&self, out: &mut String, r: &Render, title: &str) {
        let scope = r.scope;
        out.push_str(&format!(
            r#"<div class="z-toolbar" role="toolbar" aria-label="{title}">"#
        ));
        for (n, item) in self.items.iter().enumerate() {
            match item {
                ToolItem::Button(b) => {
                    let tip = b.tip.as_ref().map(|t| crate::ui::tip(r, &format!("{scope}-tooltip-{n}"), t));
                    if tip.is_some() {
                        out.push_str(r#"<span class="z-tip-host">"#);
                    }
                    let english = b.label.english();
                    out.push_str(&format!(
                        r#"<button type="button" class="z-button" data-testid="{scope}.toolbar.{}""#,
                        slug(&english)
                    ));
                    if let Some(keys) = b.shortcut.as_deref().and_then(|s| crate::command::usable_shortcut(s, b.override_browser)) {
                        out.push_str(&format!(r#" aria-keyshortcuts="{}""#, crate::render::escape(&keys)));
                    }
                    if let Some(e) = &b.effect {
                        out.push_str(&format!(r#" data-zeyn-effect="{}""#, attr(e)));
                    }
                    if let Some((attrs, _)) = &tip {
                        out.push_str(attrs);
                    }
                    out.push('>');
                    if let Some(i) = b.icon {
                        out.push_str(&i.html());
                    }
                    out.push_str(&r.text(&b.label));
                    out.push_str("</button>");
                    if let Some((_, html)) = &tip {
                        out.push_str(html);
                        out.push_str("</span>");
                    }
                }
                ToolItem::Export(e) => out.push_str(&format!(
                    r#"<button type="button" class="z-button" data-testid="{scope}.toolbar.export-{code}" data-zeyn-export="{code}">{}</button>"#,
                    r.text(&Text::key(format!("zeyn.export.{}", e.code()))),
                    code = e.code()
                )),
            }
        }
        out.push_str("</div>");
    }

    pub(crate) fn schema(&self) -> serde_json::Value {
        self.items
            .iter()
            .map(|item| match item {
                ToolItem::Button(b) => json!({
                    "type": "button",
                    "label": b.label,
                    "icon": b.icon,
                    "shortcut": b.shortcut,
                    "effect": b.effect,
                }),
                ToolItem::Export(e) => json!({ "type": "export", "format": e }),
            })
            .collect()
    }
}

/// Toolbar button being configured.
pub struct ToolButton {
    bar: Toolbar,
    spec: ButtonSpec,
}

impl ToolButton {
    pub fn icon(mut self, icon: Icon) -> Self {
        self.spec.icon = Some(icon);
        self
    }

    /// Keyboard shortcut such as `"Alt+N"`. Shortcuts the browser uses (`Ctrl+P`, `Ctrl+S`,
    /// `F5`, ...) are not bound unless the button calls [`ToolButton::override_browser`]; ones the
    /// browser never passes on (`Ctrl+N`, `Ctrl+T`, `Ctrl+W`) are never bound. Both are logged.
    pub fn shortcut(mut self, keys: impl Into<String>) -> Self {
        self.spec.shortcut = Some(keys.into());
        self
    }

    /// Takes over a shortcut the browser uses, on purpose.
    pub fn override_browser(mut self) -> Self {
        self.spec.override_browser = true;
        self
    }

    /// A tooltip for the button: shown on hover, focus and long press, read as its description.
    pub fn tip(mut self, text: impl Into<Text>) -> Self {
        self.spec.tip = Some(text.into());
        self
    }

    /// Opens the screen as a window when the button is pressed.
    pub fn opens<S: ScreenDef>(mut self, screen: S, params: S::Params) -> Self {
        self.spec.effect = Some(Window::open(screen, params));
        self
    }

    pub fn button(self, label: impl Into<Text>) -> ToolButton {
        self.finish().button(label)
    }

    pub fn export(self, format: Export) -> Toolbar {
        self.finish().export(format)
    }

    fn finish(mut self) -> Toolbar {
        self.bar
            .items
            .push(ToolItem::Button(self.spec));
        self.bar
    }
}

impl From<ToolButton> for Toolbar {
    fn from(b: ToolButton) -> Self {
        b.finish()
    }
}

#[derive(Clone, Copy, Debug)]
enum ScreenKind {
    Page,
    Window { width: u32 },
}

/// Content of a screen. Screen functions return this.
pub struct Screen {
    title: Text,
    kind: ScreenKind,
    toolbar: Option<Toolbar>,
    body: Vec<Node>,
    menu: Option<crate::menu::ContextMenu>,
    moved: Option<(&'static str, serde_json::Value)>,
    head: Option<Box<crate::seo::Head>>,
}

impl Screen {
    /// Full page screen.
    pub fn new(title: impl Into<Text>) -> Self {
        Self {
            title: title.into(),
            kind: ScreenKind::Page,
            toolbar: None,
            body: Vec::new(),
            menu: None,
            moved: None,
            head: None,
        }
    }

    /// Answers that this page lives at another screen's address now: the browser gets a permanent
    /// redirect (301) there, such as from an old slug to the current one. Params of the wrong type
    /// do not compile. To answer that nothing is there, return `Err(Error::NotFound)` instead.
    ///
    /// ```ignore
    /// if p.slug != product.slug {
    ///     return Ok(Screen::moved_to(product_page, ProductParams { slug: product.slug, n: p.n }));
    /// }
    /// ```
    pub fn moved_to<S: ScreenDef>(_screen: S, params: S::Params) -> Self {
        Self {
            moved: Some((S::META.name, params_json(&params))),
            ..Self::new("")
        }
    }

    /// Screen and params of [`Screen::moved_to`], if this screen moved.
    pub(crate) fn take_moved(&mut self) -> Option<(&'static str, serde_json::Value)> {
        self.moved.take()
    }

    fn head_mut(&mut self) -> &mut crate::seo::Head {
        self.head
            .get_or_insert_with(Default::default)
    }

    /// Summary for search results and link previews: `<meta name="description">` and
    /// `og:description`.
    pub fn description(mut self, text: impl Into<Text>) -> Self {
        self.head_mut().description = Some(text.into());
        self
    }

    /// The URL search engines should index for this page: an `https` URL, or an app path written
    /// behind `App::site_url` and the base path. Other URLs are ignored with a warning.
    pub fn canonical(mut self, url: impl Into<String>) -> Self {
        self.head_mut().canonical = crate::seo::checked(url.into(), "a canonical URL");
        self
    }

    /// The same page in another language, sent as `<link rel="alternate" hreflang="..">`:
    /// `hreflang` is a language tag such as `tr` or `zh-Hans`, or `x-default` for the page shown
    /// when no language matches, and `url` an `https` URL or an app path. List every language
    /// the page has, including its own. Bad tags or URLs are ignored with a warning, and at most
    /// [`crate::seo::MAX_ALTERNATES`] are kept.
    ///
    /// ```
    /// use zeyn::Screen;
    /// let s = Screen::new("Orders").alternate("en", "/orders").alternate("tr", "/tr/orders").alternate("x-default", "/orders");
    /// ```
    pub fn alternate(mut self, hreflang: &str, url: impl Into<String>) -> Self {
        let tag = crate::seo::valid_hreflang(hreflang);
        let url = crate::seo::checked(url.into(), "an alternate URL");
        let head = self.head_mut();
        match (tag, url) {
            (true, Some(url)) if head.alternates.len() < crate::seo::MAX_ALTERNATES => {
                head.alternates
                    .push((hreflang.to_string(), url));
            }
            (false, _) => {
                tracing::warn!("hreflang `{hreflang}` is not a language tag or x-default; ignored")
            }
            _ => {}
        }
        self
    }

    /// Image of link previews (`og:image`): an `https` URL or an app path.
    pub fn og_image(mut self, url: impl Into<String>) -> Self {
        self.head_mut().og_image = crate::seo::checked(url.into(), "an og:image URL");
        self
    }

    /// Structured data for search engines, sent as `<script type="application/ld+json">`. The
    /// browser never runs it, and the JSON is escaped so it cannot end the script element.
    pub fn json_ld(mut self, data: serde_json::Value) -> Self {
        self.head_mut().json_ld = Some(data);
        self
    }

    /// Whether search engines may index the page.
    pub fn robots(mut self, robots: crate::seo::Robots) -> Self {
        self.head_mut().robots = Some(robots);
        self
    }

    /// Head tags of the page (description, canonical, alternates, preview image, robots, JSON-LD), empty
    /// when the screen sets none.
    pub fn head_html(&self, r: &Render, site: &str, prefix: &str) -> String {
        self.head
            .as_ref()
            .map(|h| h.render(r, site, prefix))
            .unwrap_or_default()
    }

    /// Screen opened as a window.
    pub fn window(title: impl Into<Text>) -> Self {
        Self {
            kind: ScreenKind::Window { width: 560 },
            ..Self::new(title)
        }
    }

    /// Window width in pixels. No effect on full page screens.
    pub fn width(mut self, px: u32) -> Self {
        if let ScreenKind::Window { width } = &mut self.kind {
            *width = px;
        }
        self
    }

    pub fn toolbar<F, R>(mut self, build: F) -> Self
    where
        F: FnOnce(Toolbar) -> R,
        R: Into<Toolbar>,
    {
        self.toolbar = Some(build(Toolbar::default()).into());
        self
    }

    pub fn body(mut self, node: impl Into<Node>) -> Self {
        self.body.push(node.into());
        self
    }

    /// Context menu for the empty space of the screen (not over rows, headers or inputs).
    pub fn context_menu(mut self, menu: crate::menu::ContextMenu) -> Self {
        self.menu = Some(menu);
        self
    }

    /// Takes the action item at `path` of the screen's context menu, to run it.
    pub fn menu_call(&self, path: &str) -> Option<RowCall> {
        self.menu.as_ref()?.take(path)
    }

    pub fn title(&self) -> &Text {
        &self.title
    }

    pub fn nodes(&self) -> &[Node] {
        &self.body
    }

    /// Renders the screen in English with no params and no preloaded rows. For tests and tools.
    pub fn html(&self, meta: &ScreenMeta) -> String {
        self.render(
            &Render::english(meta.name),
            meta,
            &serde_json::Value::Null,
            &HashMap::new(),
        )
    }

    /// Renders the screen. `loaded` holds the first page of grids by node path (`"0"`, `"1.2"`).
    pub fn render(
        &self,
        r: &Render,
        meta: &ScreenMeta,
        params: &serde_json::Value,
        loaded: &HashMap<String, LoadedPage>,
    ) -> String {
        let scope = meta.name;
        let r = Render {
            scope,
            loaded: Some(loaded),
            ..*r
        };
        let title = r.text(&self.title);
        let params = match self
            .menu
            .as_ref()
            .map(|m| m.to_json(&r))
        {
            Some(items)
                if items
                    .as_array()
                    .is_some_and(|a| !a.is_empty()) =>
            {
                format!(r#"{}" data-zeyn-menu="{}"#, attr(params), attr(&items))
            }
            _ => attr(params),
        };
        let mut out = String::new();
        let close = match self.kind {
            ScreenKind::Page => {
                out.push_str(&format!(
                    r#"<section class="z-screen" data-zeyn-screen="{scope}" data-zeyn-params="{params}" aria-labelledby="{scope}-title"><h1 id="{scope}-title">{title}</h1>"#
                ));
                "</section>"
            }
            ScreenKind::Window { width } => {
                out.push_str(&format!(
                    r#"<div class="z-window" role="dialog" aria-modal="true" data-zeyn-screen="{scope}" data-zeyn-params="{params}" aria-labelledby="{scope}-title" style="--z-width:{width}px"><h2 id="{scope}-title">{title}</h2>"#
                ));
                "</div>"
            }
        };
        if let Some(t) = &self.toolbar {
            t.render(&mut out, &r, &title);
        }
        for (i, node) in self.body.iter().enumerate() {
            crate::ui::render_node(&mut out, &r, &i.to_string(), node);
        }
        out.push_str(close);
        out
    }

    /// Screen schema used by MCP tools, test generation and validation.
    pub fn schema(&self, meta: &ScreenMeta) -> serde_json::Value {
        let (kind, width) = match self.kind {
            ScreenKind::Page => ("page", None),
            ScreenKind::Window { width } => ("window", Some(width)),
        };
        json!({
            "screen": meta,
            "title": self.title,
            "kind": kind,
            "width": width,
            "toolbar": self.toolbar.as_ref().map(Toolbar::schema),
            "body": self.body.iter().map(Node::schema).collect::<Vec<_>>(),
        })
    }
}
