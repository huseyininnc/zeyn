    fn passkey(&self, credential_id: &[u8]) -> BoxFuture<Result<Option<(String, Passkey)>>> {
        let (s, id) = (self.clone(), b64url(credential_id));
        Box::pin(async move {
            let rows =
                s.db.rows(s.sql(
                    "SELECT user_id, data FROM {p}user_passkeys WHERE credential_id = ?",
                    vec![Arg::Text(id)],
                    &[Col::Text, Col::Text],
                ))
                .await?;
            Ok(rows.into_iter().next().and_then(|r| {
                let mut c = r.into_iter();
                let user = text(&mut c)?;
                let data = serde_json::from_str(&text(&mut c)?).ok()?;
                Some((user, data))
            }))
        })
    }

    fn save_passkey(&self, user_id: &str, passkey: &Passkey) -> BoxFuture<Result<()>> {
        let (s, u, p) = (self.clone(), user_id.to_string(), passkey.clone());
        Box::pin(async move {
            let id = b64url(&p.credential_id);
            let data = serde_json::to_string(&p).map_err(|e| Error::Internal(e.to_string()))?;
            let changed = s
                .run(
                    "UPDATE {p}user_passkeys SET data = ? WHERE credential_id = ? AND user_id = ?",
                    vec![
                        Arg::Text(data.clone()),
                        Arg::Text(id.clone()),
                        Arg::Text(u.clone()),
                    ],
                )
                .await?;
            if changed == 0 {
                s.run(
                    "INSERT INTO {p}user_passkeys (credential_id, user_id, data) VALUES (?, ?, ?)",
                    vec![Arg::Text(id), Arg::Text(u), Arg::Text(data)],
                )
                .await
                .map_err(conflict)?;
            }
            Ok(())
        })
    }

