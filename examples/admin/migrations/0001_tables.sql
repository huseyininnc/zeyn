CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(200) NOT NULL,
    city VARCHAR(80) NOT NULL,
    segment VARCHAR(20) NOT NULL,
    active BOOLEAN NOT NULL,
    since DATE NOT NULL DEFAULT CURRENT_DATE,
    version BIGINT NOT NULL DEFAULT 1
);

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(20) NOT NULL,
    name VARCHAR(200) NOT NULL,
    category VARCHAR(20) NOT NULL,
    price BIGINT NOT NULL,
    price_currency VARCHAR(3) NOT NULL,
    stock BIGINT NOT NULL,
    active BOOLEAN NOT NULL,
    version BIGINT NOT NULL DEFAULT 1
);

CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number VARCHAR(20) NOT NULL,
    customer_id BIGINT NOT NULL REFERENCES customers (id),
    customer_name VARCHAR(120) NOT NULL,
    placed DATE NOT NULL,
    status VARCHAR(20) NOT NULL,
    items BIGINT NOT NULL,
    total BIGINT NOT NULL,
    total_currency VARCHAR(3) NOT NULL,
    notes VARCHAR(500),
    version BIGINT NOT NULL DEFAULT 1
);

CREATE INDEX orders_placed ON orders (placed, id);
CREATE INDEX orders_status ON orders (status, id);
CREATE INDEX orders_customer ON orders (customer_id, id);

CREATE TABLE order_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders (id),
    at TIMESTAMPTZ(3) NOT NULL,
    user_name VARCHAR(120) NOT NULL,
    kind VARCHAR(20) NOT NULL,
    detail VARCHAR(2000) NOT NULL,
    version BIGINT NOT NULL DEFAULT 1
);

CREATE INDEX order_events_order ON order_events (order_id, at);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(200) NOT NULL,
    role VARCHAR(20) NOT NULL,
    active BOOLEAN NOT NULL,
    version BIGINT NOT NULL DEFAULT 1
);

CREATE TABLE settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company VARCHAR(120) NOT NULL,
    support_email VARCHAR(200) NOT NULL,
    ship_within_days BIGINT NOT NULL,
    low_stock BIGINT NOT NULL,
    notify_new_orders BOOLEAN NOT NULL,
    weekly_report BOOLEAN NOT NULL,
    version BIGINT NOT NULL DEFAULT 1
);
