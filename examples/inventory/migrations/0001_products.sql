SELECT 'P-' || lpad(i::text, 4, '0'),
       (ARRAY['Black tea', 'Green tea', 'Coffee beans', 'Olive oil', 'Honey', 'Hazelnuts', 'Dried apricots', 'Feta cheese'])[i % 8 + 1] || ' ' || i,
       (ARRAY['Kg', 'Piece', 'Liter'])[i % 3 + 1],
       i * 1275,
       'TRY',
       (i * 7) % 40,
       i % 9 <> 0
FROM generate_series(1, 120) AS i;
